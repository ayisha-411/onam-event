-- Profiles
DROP POLICY IF EXISTS "select_own_profile" ON profiles;
CREATE POLICY "select_own_profile" ON profiles FOR SELECT TO authenticated USING (auth.uid() = id);
DROP POLICY IF EXISTS "insert_own_profile" ON profiles;
CREATE POLICY "insert_own_profile" ON profiles FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);
DROP POLICY IF EXISTS "update_own_profile" ON profiles;
CREATE POLICY "update_own_profile" ON profiles FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

-- Events
DROP POLICY IF EXISTS "select_events" ON events;
CREATE POLICY "select_events" ON events FOR SELECT TO authenticated USING (
  organizer_id = auth.uid()
  OR visibility = 'public'
  OR EXISTS (SELECT 1 FROM participants p WHERE p.event_id = events.id AND p.user_id = auth.uid())
);
DROP POLICY IF EXISTS "insert_events" ON events;
CREATE POLICY "insert_events" ON events FOR INSERT TO authenticated WITH CHECK (organizer_id = auth.uid());
DROP POLICY IF EXISTS "update_events" ON events;
CREATE POLICY "update_events" ON events FOR UPDATE TO authenticated USING (organizer_id = auth.uid()) WITH CHECK (organizer_id = auth.uid());
DROP POLICY IF EXISTS "delete_events" ON events;
CREATE POLICY "delete_events" ON events FOR DELETE TO authenticated USING (organizer_id = auth.uid());

-- Participants
DROP POLICY IF EXISTS "select_participants" ON participants;
CREATE POLICY "select_participants" ON participants FOR SELECT TO authenticated USING (
  user_id = auth.uid()
  OR EXISTS (SELECT 1 FROM events e WHERE e.id = participants.event_id AND e.organizer_id = auth.uid())
  OR EXISTS (
    SELECT 1 FROM participants p2
    WHERE p2.event_id = participants.event_id AND p2.user_id = auth.uid()
  )
);
DROP POLICY IF EXISTS "insert_participants" ON participants;
CREATE POLICY "insert_participants" ON participants FOR INSERT TO authenticated WITH CHECK (
  user_id = auth.uid()
  OR EXISTS (SELECT 1 FROM events e WHERE e.id = participants.event_id AND e.organizer_id = auth.uid())
);
DROP POLICY IF EXISTS "update_participants" ON participants;
CREATE POLICY "update_participants" ON participants FOR UPDATE TO authenticated USING (
  EXISTS (SELECT 1 FROM events e WHERE e.id = participants.event_id AND e.organizer_id = auth.uid())
