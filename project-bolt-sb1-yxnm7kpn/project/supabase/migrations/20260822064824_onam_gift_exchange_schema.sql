/*
# Onam Gift Exchange Platform Schema

1. Overview
   Multi-user platform for organizing secret gift exchanges during Onam.
   Users sign in with email/password. Each user owns their events, participations, wishlists, and assignments.

2. New Tables
   - `profiles`: extended user info (display name, avatar, phone, language, accessibility prefs)
   - `events`: gift exchange events (name, description, date, venue, category, visibility, budget range, currency, banner color)
   - `participants`: join table between events and users (status, joined_at)
   - `wishlists`: gift preferences per participant (brand, color, hobbies, size, allergies, notes)
   - `assignments`: secret santa assignments (giver -> receiver, generated by organizer)
   - `gift_tracking`: status of gift from purchase to delivery
   - `memory_wall_posts`: photos and memories shared in an event
   - `leaderboard_entries`: gamification points per participant
   - `notifications`: in-app notifications for users

3. Security
   - RLS enabled on every table.
   - Profiles: owner-scoped CRUD.
   - Events: owner can CRUD; participants can SELECT events they joined; public events visible to all authenticated.
   - Participants: event organizer can insert/update/delete; participants can SELECT.
   - Wishlists: owner-scoped; event organizer and assigned giver can read.
   - Assignments: only the giver and the event organizer can see.
   - Gift tracking: giver and organizer can update/read.
   - Memory wall: event participants can read; post author can delete.
   - Leaderboard: readable by event participants.
   - Notifications: owner-scoped.
*/

-- ===== TABLES FIRST =====

CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text NOT NULL DEFAULT '',
  avatar_url text,
  phone text,
  preferred_language text DEFAULT 'en',
  high_contrast boolean DEFAULT false,
  font_size text DEFAULT 'medium',
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organizer_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text,
  event_date date NOT NULL,
  event_time text,
  venue text,
  category text DEFAULT 'family',
  visibility text DEFAULT 'private',
  min_budget numeric DEFAULT 0,
  max_budget numeric DEFAULT 100,
  currency text DEFAULT 'INR',
  banner_color text DEFAULT '#d4a017',
  invite_code text UNIQUE,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS participants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  status text DEFAULT 'pending',
  joined_at timestamptz DEFAULT now(),
  UNIQUE (event_id, user_id)
);

CREATE TABLE IF NOT EXISTS assignments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  giver_user_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  receiver_user_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at timestamptz DEFAULT now(),
  UNIQUE (event_id, giver_user_id),
  UNIQUE (event_id, receiver_user_id)
);

CREATE TABLE IF NOT EXISTS wishlists (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  participant_id uuid NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  event_id uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  favorite_brands text,
  favorite_colors text,
  hobbies text,
  clothing_size text,
  allergies text,
  custom_notes text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gift_tracking (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id uuid NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  event_id uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  giver_user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  status text DEFAULT 'not_started',
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS memory_wall_posts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  title text,
  image_url text,
  caption text,
  likes integer DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS leaderboard_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  points integer DEFAULT 0,
  badge text,
  UNIQUE (event_id, user_id)
);

CREATE TABLE IF NOT EXISTS notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  event_id uuid REFERENCES events(id) ON DELETE CASCADE,
  message text NOT NULL,
  type text DEFAULT 'info',
  read boolean DEFAULT false,
  created_at timestamptz DEFAULT now()
);

